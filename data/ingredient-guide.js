const guides = {}
entries.forEach(([picture, names, preparation]) => {
  names.split('|').forEach(name => { guides[name] = { image: `/assets/images/ingredients/${picture}.jpg`, preparation } })
})

function getIngredientGuide(name) {
  return guides[name] || null
}

function decorateIngredient(item) {
  const guide = getIngredientGuide(item.name)
  return guide ? { ...item, ...guide } : { ...item, image: '', preparation: '请按食品包装和本菜步骤准备。' }
}

module.exports = { getIngredientGuide, decorateIngredient }
